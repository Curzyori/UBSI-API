-- ============================================================
-- CLEAN GROUP EXPERIENCE — Bot Telegram USRC v2.1
-- 3 tabel pendukung: ghost log (audit), receipts (resi anti-rekayasa),
-- ephemeral msgs (jadwal/list yang menguap + preview kumpul).
-- Pola konsisten ubsi_task_submissions: RLS enable, tanpa policy
-- => hanya service_role (worker) yang bisa akses.
-- Jalankan di Supabase SQL Editor.
-- ============================================================

-- 1. GHOST LOG — jejak audit semua yang menguap dari grup
create table if not exists public.ubsi_ghost_log (
  id          bigint generated by default as identity primary key,
  bot         text not null,                -- 'gudang' | 'absen' | 'stats' | 'master'
  chat_id     bigint,
  thread_id   bigint,
  user_id     bigint,
  user_name   text,
  nim         text,
  command     text,                         -- teks command / aksi ('kumpul_ok', 'btn_jadwal_today', 'jadwal_kedaluwarsa', ...)
  detail      text,                         -- ringkasan bebas
  outcome     text,                         -- 'success' | 'failed' | 'cancelled' | 'expired' | 'dm_fallback'
  created_at  timestamptz not null default now()
);
alter table public.ubsi_ghost_log enable row level security;
create index if not exists idx_ghost_log_command on public.ubsi_ghost_log (command);
create index if not exists idx_ghost_log_nim     on public.ubsi_ghost_log (nim);
create index if not exists idx_ghost_log_created on public.ubsi_ghost_log (created_at desc);

-- 2. RECEIPTS — resi anti-rekayasa untuk bukti kumpul/absen
create table if not exists public.ubsi_receipts (
  id         bigint generated by default as identity primary key,
  code       text not null unique,          -- 'KMP-7F3A' / 'ABS-9QX2'
  type       text not null,                 -- 'kumpul' | 'absen'
  user_id    bigint,
  nim        text,
  full_name  text,
  summary    text,                          -- deskripsi satu kalimat
  ref_id     bigint,                        -- id baris sumber (ubsi_task_submissions.id, dst)
  created_at timestamptz not null default now()
);
alter table public.ubsi_receipts enable row level security;
create index if not exists idx_receipts_code on public.ubsi_receipts (code);

-- 3. EPHEMERAL MSGS — pesan bot yang dijadwalkan menguap
create table if not exists public.ubsi_ephemeral_msgs (
  id          bigint generated by default as identity primary key,
  bot         text not null,                -- 'absen' | 'gudang'
  chat_id     bigint not null,
  message_id  bigint not null,              -- pesan bot yang akan dihapus
  thread_id   bigint,
  user_id     bigint,                       -- pemohon
  user_name   text,
  kind        text not null,                -- 'jadwal' | 'kumpul_preview'
  ref_id      bigint,                       -- subId untuk kumpul_preview
  payload     jsonb,                        -- item list untuk tick countdown
  cmd_msg_id  bigint,                       -- pesan command user yang ikut dihapus
  created_at  timestamptz not null default now(),
  expires_at  timestamptz
);
alter table public.ubsi_ephemeral_msgs enable row level security;
create index if not exists idx_ephemeral_expires on public.ubsi_ephemeral_msgs (expires_at);
create index if not exists idx_ephemeral_kind_ref on public.ubsi_ephemeral_msgs (kind, ref_id);
